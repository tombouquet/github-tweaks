// Copies file icons from the material-icon-theme npm package into icons/ and
// writes src/file-icons-data.js. Run from the repo root:
//   npm pack material-icon-theme && tar xzf material-icon-theme-*.tgz
//   node scripts/vendor-icons.js package
const fs = require('fs');
const path = require('path');

const pkg = path.resolve(process.argv[2]);
const theme = JSON.parse(fs.readFileSync(path.join(pkg, 'dist/material-icons.json'), 'utf8'));
const used = new Set();
const file = (id) => {
  const name = path.basename(theme.iconDefinitions[id].iconPath, '.svg');
  used.add(name);
  return name;
};
const pick = (map = {}) => Object.fromEntries(Object.entries(map).map(([key, id]) => [key.toLowerCase(), file(id)]));

const data = {
  file: file(theme.file),
  names: pick(theme.fileNames),
  exts: pick(theme.fileExtensions),
  light: { names: pick(theme.light.fileNames), exts: pick(theme.light.fileExtensions) },
};

fs.rmSync('icons', { recursive: true, force: true });
fs.mkdirSync('icons');
for (const name of used) fs.copyFileSync(path.join(pkg, 'icons', `${name}.svg`), path.join('icons', `${name}.svg`));
fs.copyFileSync(path.join(pkg, 'LICENSE'), path.join('icons', 'LICENSE'));
fs.writeFileSync(
  'src/file-icons-data.js',
  `// Generated by scripts/vendor-icons.js from material-icon-theme ${require(path.join(pkg, 'package.json')).version} (MIT).\nglobalThis.GH_TWEAKS_ICONS = ${JSON.stringify(data)};\n`,
);
console.log(`${used.size} icons`);
